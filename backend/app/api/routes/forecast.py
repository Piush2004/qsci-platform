"""
Forecasts API — Demand Forecasting Endpoints.

Serves forecast data generated by the AI Engine for dashboards
and the Planner Workspace.
"""
from fastapi import APIRouter, Depends
from backend.app.api.dependencies import get_current_user, CurrentUser
from backend.app.services.ai_engine import ai_engine

router = APIRouter()


@router.get("/forecasts")
async def list_forecasts(
    current_user: CurrentUser = Depends(get_current_user),
):
    """
    Return the latest AI-generated forecasts across all SKUs.
    In production, this queries TimescaleDB with tenant filtering.
    """
    forecasts = ai_engine.generate_mock_forecasts(count=8)
    return {"total": len(forecasts), "items": forecasts}


@router.get("/forecasts/{forecast_id}")
async def get_forecast(
    forecast_id: str,
    current_user: CurrentUser = Depends(get_current_user),
):
    """Get a single forecast by ID."""
    forecasts = ai_engine.generate_mock_forecasts(count=8)
    fc = next((f for f in forecasts if f["id"] == forecast_id), None)
    if not fc:
        from backend.app.core.errors import not_found
        raise not_found("Forecast", forecast_id)
    return fc
